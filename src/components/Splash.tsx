import { Logo } from './Logo'

/**
 * Заставка при первом заходе: логотип собирается из секций.
 *
 * Ограничена намеренно и сильно. Сайт открывает служба безопасности партнёра,
 * чтобы быстро проверить компанию, — заслонка перед контентом здесь работает
 * против задачи. Поэтому:
 *
 * - показывается один раз за сессию, а не на каждой странице;
 * - живёт фиксированные 1.4 секунды и уходит, ничего не дожидаясь: это
 *   не «загрузчик», страница под ней уже отрисована. Гасить по готовности
 *   сети нельзя — на медленном канале заставка превратилась бы в настоящую
 *   задержку;
 * - при `prefers-reduced-motion` не показывается вовсе;
 * - `aria-hidden`: читалке экрана она не нужна.
 *
 * Разметка отдаётся сервером, а гаснет заставка чистым CSS. На React
 * состоянии она появлялась бы уже после гидратации — то есть человек видел бы
 * контент, потом заслонку поверх него, потом снова контент. Решение о показе
 * принимает крошечный скрипт в `<head>`: он выполняется до первой отрисовки
 * и успевает выключить заставку тем, кто её уже видел.
 *
 * Без JavaScript заставка отработает один раз и погаснет сама — контент
 * от этого не пострадает.
 */

/** Скрипт идёт до отрисовки: иначе повторный заход моргнёт заслонкой. */
const DECIDE = `(function(){try{
  var seen = sessionStorage.getItem('armmaks-splash');
  if (seen) { document.documentElement.dataset.splash = 'off'; return; }
  sessionStorage.setItem('armmaks-splash','1');
}catch(e){}})()`

export function Splash() {
  return (
    <>
      <script dangerouslySetInnerHTML={{ __html: DECIDE }} />
      <div aria-hidden className="splash">
        {/* Логотип небольшой: крупный на пустом экране читается как баннер,
            а заставка живёт полторы секунды и должна быть скромной. */}
        <div className="px-8 text-white">
          <Logo size="sm" animated />
        </div>
      </div>
    </>
  )
}
